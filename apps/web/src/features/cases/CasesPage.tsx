/** URL search state of `/p/:key/cases`. */
export interface CasesSearch {
  suite?: string;
  q?: string;
  page?: number;
}

type CaseRow = RouterOutputs['cases']['list']['items'][number];

const PAGE_SIZE = 25;
const PRIORITIES = ['P0', 'P1', 'P2', 'P3'] as const;
const STATUSES = ['draft', 'ready', 'deprecated'] as const;
const VERDICT_FILTERS = [
  ['passed', 'Passed'],
  ['failed', 'Failed'],
  ['flaky', 'Flaky'],
  ['needs-review', 'Review'],
  ['blocked', 'Blocked'],
  ['skipped', 'Skipped'],
  ['none', 'Not run yet'],
] as const;
/** Tag that marks a case drafted by System 2; shown as "generated by S2 · needs review". */
export const S2_GENERATED_TAG = 's2-generated';

/** Learned-script label for the list (`Ready · staging`, `Healed · needs approval`, `Not learned yet`, `—`). */
export function learnedLabel(c: Pick<CaseRow, 'learned' | 'status'>): string {
  if (c.learned.length === 0 || c.status === 'draft') return '—';
  const review = c.learned.find((l) => l.status === 'needs-review');
  if (review) return 'Healed · needs approval';
  const current = c.learned.find((l) => l.status === 'current');
  if (current) return `Ready · ${current.environmentName}`;
  const stale = c.learned.find((l) => l.status === 'stale');
  if (stale) return `Outdated · ${stale.environmentName}`;
  return 'Not learned yet';
}

function useDebounced(callback: (value: string) => void, ms: number) {
  const timer = useRef<ReturnType<typeof setTimeout> | undefined>(undefined);
  const latest = useRef(callback);
  latest.current = callback;
  useEffect(() => () => clearTimeout(timer.current), []);
  return useCallback(
    (value: string) => {
      clearTimeout(timer.current);
      timer.current = setTimeout(() => latest.current(value), ms);
    },
    [ms],
  );
}

function FilterMenu({
  label,
  value,
  options,
  onChange,
}: {
  label: string;
  value: string | undefined;
  options: ReadonlyArray<readonly [value: string, label: string]>;
  onChange: (value: string | undefined) => void;
}) {
  const active = value !== undefined ? options.find(([v]) => v === value)?.[1] : undefined;
  return (
    <DropdownMenu>
      <DropdownTrigger asChild>
        <button
          type="button"
          className={cn(
            'min-h-[44px] rounded-pill border px-3 text-[13px] text-fg',
            active !== undefined ? 'border-primary bg-primary-soft text-primary-text' : 'border-line-input bg-surface',
          )}
        >
          {label}
          {active !== undefined ? `: ${active}` : ''} ▾
        </button>
      </DropdownTrigger>
      <DropdownContent>
        <DropdownRadioGroup value={value ?? ''} onValueChange={(v) => onChange(v === '' ? undefined : v)}>
          <DropdownRadioItem value="">Any</DropdownRadioItem>
          <DropdownSeparator />
          {options.map(([v, text]) => (
            <DropdownRadioItem key={v} value={v}>
              {text}
            </DropdownRadioItem>
          ))}
        </DropdownRadioGroup>
      </DropdownContent>
    </DropdownMenu>
  );
}

function TagDialog({
  open,
  onOpenChange,
  count,
  busy,
  onApply,
}: {
  open: boolean;
  onOpenChange: (open: boolean) => void;
  count: number;
  busy: boolean;
  onApply: (add: string[], remove: string[]) => void;
}) {
  const [add, setAdd] = useState('');
  const [remove, setRemove] = useState('');
  const parse = (s: string) => s.split(',').map((t) => t.trim()).filter((t) => t !== '');
  const addTags = parse(add);
  const removeTags = parse(remove);
  return (
    <Dialog
      open={open}
      onOpenChange={onOpenChange}
      title="Tag test cases"
      description={`Applies to ${count} selected test case${count === 1 ? '' : 's'}. Separate tags with commas.`}
      footer={
        <>
          <Button variant="secondary" onClick={() => onOpenChange(false)}>
            Cancel
          </Button>
          <Button
            variant="primary"
            disabled={busy || (addTags.length === 0 && removeTags.length === 0)}
            onClick={() => onApply(addTags, removeTags)}
          >
            Apply tags
          </Button>
        </>
      }
    >
      <div className="flex flex-col gap-3.5">
        <Field label="Add tags">{(id) => <Input id={id} mono value={add} placeholder="checkout, smoke" onChange={(e) => setAdd(e.target.value)} />}</Field>
        <Field label="Remove tags">{(id) => <Input id={id} mono value={remove} onChange={(e) => setRemove(e.target.value)} />}</Field>
      </div>
    </Dialog>
  );
}

interface CasesPageProps {
  projectKey: string;
  search: CasesSearch;
  /** Writes the next URL search; `replace` avoids a history entry. */
  onSearch: (next: CasesSearch, opts?: { replace?: boolean }) => void;
  /** In-app navigation to a path. */
  navigate: (to: string) => void;
}

/** Test cases screen: suite tree, filterable and selectable case table, bulk actions and the run launcher. */
export function CasesPage({ projectKey, search, onSearch, navigate }: CasesPageProps) {
  const utils = trpc.useUtils();
  const projectName = useProjects().data?.find((p) => p.key === projectKey)?.name;
  const q = search.q ?? '';
  const page = search.page ?? 1;
  const suiteId = search.suite;

  const [draftQ, setDraftQ] = useState(q);
  /** Last value this page wrote to the URL, so only external changes (back/forward) overwrite the input. */
  const committedQ = useRef(q);
  useEffect(() => {
    if (q !== committedQ.current) {
      committedQ.current = q;
      setDraftQ(q);
    }
  }, [q]);
  const commitQ = useDebounced(
    (value) => {
      const next = value.trim();
      committedQ.current = next;
      onSearch({ ...(suiteId !== undefined ? { suite: suiteId } : {}), ...(next !== '' ? { q: next } : {}) });
    },
    300,
  );

  const list = trpc.cases.list.useQuery(
    { projectKey, ...(suiteId !== undefined ? { suiteId } : {}), ...(q !== '' ? { query: q } : {}), page, pageSize: PAGE_SIZE, sort: { by: 'key', dir: 'asc' } },
    { placeholderData: keepPreviousData },
  );
  const sync = trpc.syncStatus.useQuery({ projectKey });
  const tree = trpc.suites.tree.useQuery({ projectKey });

  const [lastResult, setLastResult] = useState<string | undefined>(undefined);
  const items = useMemo(() => {
    const all = list.data?.items ?? [];
    if (lastResult === undefined) return all;
    return all.filter((c) => (c.lastResult?.verdict ?? 'none') === lastResult);
  }, [list.data, lastResult]);
  const total = list.data?.total ?? 0;
  const pageCount = Math.max(1, Math.ceil(total / PAGE_SIZE));
  const owners = useMemo(() => {
    const set = new Set<string>();
    for (const c of list.data?.items ?? []) if (c.owner !== undefined && c.owner !== '') set.add(c.owner);
    const current = fieldValue(q, 'owner');
    if (current !== undefined) set.add(current);
    return [...set].sort();
  }, [list.data, q]);

  // selection: case id -> key
  const [selected, setSelected] = useState<Map<string, string>>(new Map());
  useEffect(() => setSelected(new Map()), [suiteId, q]);
  const toggle = (c: CaseRow) =>
    setSelected((prev) => {
      const next = new Map(prev);
      if (next.has(c.id)) next.delete(c.id);
      else next.set(c.id, c.key);
      return next;
    });
  const allOnPage = items.length > 0 && items.every((c) => selected.has(c.id));
  const toggleAll = () =>
    setSelected((prev) => {
      const next = new Map(prev);
      for (const c of items) {
        if (allOnPage) next.delete(c.id);
        else next.set(c.id, c.key);
      }
      return next;
    });

  const rowsRef = useRef<HTMLTableSectionElement>(null);
  const onRowsKey = (e: KeyboardEvent<HTMLTableSectionElement>) => {
    if (e.key !== 'ArrowDown' && e.key !== 'ArrowUp') return;
    const boxes = [...(rowsRef.current?.querySelectorAll<HTMLInputElement>('input[type="checkbox"]') ?? [])];
    const row = (e.target as HTMLElement).closest('tr');
    const here = boxes.findIndex((b) => b.closest('tr') === row);
    if (here === -1) return;
    e.preventDefault();
    boxes[Math.max(0, Math.min(boxes.length - 1, here + (e.key === 'ArrowDown' ? 1 : -1)))]?.focus();
  };

  const [notice, setNotice] = useState<{ tone: 'success' | 'danger'; text: string } | null>(null);
  const afterBulk = async (text: string) => {
    setNotice({ tone: 'success', text });
    setSelected(new Map());
    await Promise.all([utils.cases.list.invalidate(), utils.suites.tree.invalidate()]);
  };
  const bulk = trpc.cases.bulk.useMutation({ onError: (err) => setNotice({ tone: 'danger', text: errorMessage(err) }) });
  const ids = [...selected.keys()];
  const n = selected.size;
  const [tagOpen, setTagOpen] = useState(false);
  const [runOpen, setRunOpen] = useState(false);
  const [planOpen, setPlanOpen] = useState(false);

  const create = trpc.cases.create.useMutation({
    onSuccess: (c) => navigate(`/p/${encodeURIComponent(projectKey)}/cases/${encodeURIComponent(c.key)}`),
    onError: (err) => setNotice({ tone: 'danger', text: errorMessage(err) }),
  });

  const hrefFor = (id: string | undefined) => {
    const params = new URLSearchParams();
    if (id !== undefined) params.set('suite', id);
    const s = params.toString();
    return `/p/${encodeURIComponent(projectKey)}/cases${s === '' ? '' : `?${s}`}`;
  };

  const setQuery = (next: string) => {
    committedQ.current = next;
    setDraftQ(next);
    onSearch({ ...(suiteId !== undefined ? { suite: suiteId } : {}), ...(next !== '' ? { q: next } : {}) });
  };
  const setField = (field: string, term: string | undefined) => setQuery(setFieldTerm(draftQ, field, term));

  const onTitle = (key: string) => (e: MouseEvent<HTMLAnchorElement>) => {
    if (e.button !== 0 || e.metaKey || e.ctrlKey || e.shiftKey || e.altKey) return;
    e.preventDefault();
    navigate(`/p/${encodeURIComponent(projectKey)}/cases/${encodeURIComponent(key)}`);
  };

  const [importing, setImporting] = useState(false);
  const flatSuites = flattenSuites(tree.data?.tree ?? []);
  const header = (
    <PageHeader
      eyebrow={projectName !== undefined ? `${projectKey} · ${projectName}` : projectKey}
      title="Test cases"
      actions={
        <>
        <Button onClick={() => setImporting(true)}>Import</Button>
          <GenerateFromStory projectKey={projectKey} navigate={navigate} {...(suiteId !== undefined ? { suiteId } : {})} />
          <Button disabled title="Recording arrives with S-060">
            Record in browser
          </Button>
          <Button
            variant="primary"
            disabled={create.isPending}
            onClick={() =>
              create.mutate({
                projectKey,
                title: 'Untitled test case',
                status: 'draft',
                steps: [{ action: 'Describe the first step' }],
                ...(suiteId !== undefined ? { suiteId } : {}),
              })
            }
          >
            New test case
          </Button>
        </>
      }
    />
  );

  const clean = sync.data?.clean;
  return (
    <>
      {header}
      <ImportWizard open={importing} onOpenChange={setImporting} projectKey={projectKey} {...(suiteId !== undefined ? { suiteId } : {})} />
      <div className="flex flex-wrap items-start gap-5">
        <SuiteTree
          projectKey={projectKey}
          activeSuite={suiteId}
          hrefFor={hrefFor}
          onSelect={(id) => onSearch({ ...(id !== undefined ? { suite: id } : {}), ...(q !== '' ? { q } : {}) })}
          onNavigate={navigate}
          className="max-w-[280px] flex-[1_1_220px]"
        />
        <Card aria-label="Case list" className="flex min-w-0 flex-[999_1_560px] flex-col">
          <div className="flex flex-wrap items-center gap-2.5 border-b border-divider px-4 py-3.5">
            <QueryInput
              label="Filter"
              value={draftQ}
              placeholder="tags:checkout AND priority<=P1"
              onChange={(v) => {
                setDraftQ(v);
                commitQ(v);
              }}
            />
            <FilterMenu
              label="Priority"
              value={fieldValue(q, 'priority')}
              options={PRIORITIES.map((p) => [p, p] as const)}
              onChange={(v) => setField('priority', v === undefined ? undefined : `priority=${v}`)}
            />
            <FilterMenu label="Last result" value={lastResult} options={VERDICT_FILTERS} onChange={setLastResult} />
            <FilterMenu
              label="Owner"
              value={fieldValue(q, 'owner')}
              options={owners.map((o) => [o, o] as const)}
              onChange={(v) => setField('owner', v === undefined ? undefined : `owner:${quoteValue(v)}`)}
            />
            <FilterMenu
              label="Status"
              value={fieldValue(q, 'status')}
              options={STATUSES.map((s) => [s, s] as const)}
              onChange={(v) => setField('status', v === undefined ? undefined : `status:${v}`)}
            />
          </div>
          <div className="flex flex-wrap items-center justify-between gap-2.5 border-b border-divider bg-surface-subtle px-4 py-2.5 text-[13px]">
            <div className="flex flex-wrap items-center gap-2" role="toolbar" aria-label="Bulk actions">
              {n > 0 ? <strong>{n} selected</strong> : <span className="text-muted">No cases selected</span>}
              <span aria-hidden="true">·</span>
              <Button size="sm" disabled={n === 0} onClick={() => setPlanOpen(true)}>
                Add to plan
              </Button>
              <DropdownMenu>
                <DropdownTrigger asChild>
                  <Button size="sm" disabled={n === 0 || bulk.isPending}>
                    Move
                  </Button>
                </DropdownTrigger>
                <DropdownContent>
                  <DropdownItem
                    onSelect={() => bulk.mutate({ ids, action: 'move', suiteId: null }, { onSuccess: () => void afterBulk(`Moved ${n} cases out of their suites`) })}
                  >
                    No suite
                  </DropdownItem>
                  {flatSuites.length > 0 && <DropdownSeparator />}
                  {flatSuites.map((s) => (
                    <DropdownItem
                      key={s.id}
                      style={{ paddingLeft: 12 + s.depth * 14 }}
                      onSelect={() => bulk.mutate({ ids, action: 'move', suiteId: s.id }, { onSuccess: () => void afterBulk(`Moved ${n} cases to ${s.name}`) })}
                    >
                      {s.name}
                    </DropdownItem>
                  ))}
                </DropdownContent>
              </DropdownMenu>
              <Button size="sm" disabled={n === 0 || bulk.isPending} onClick={() => setTagOpen(true)}>
                Tag
              </Button>
              <Button size="sm" variant="primary" disabled={n === 0} onClick={() => setRunOpen(true)}>
                Run now
              </Button>
            </div>
            <span className="text-secondary">
              {clean === undefined ? (
                sync.isError ? (
                  'Sync status unavailable'
                ) : (
                  <Skeleton className="inline-block h-4 w-40 align-middle" />
                )
              ) : clean ? (
                <>
                  Synced with <span className="font-mono">.s1pilot/</span> in git · clean
                </>
              ) : (
                <>
                  <span className="font-mono">.s1pilot/</span> has {sync.data?.changedFiles.length ?? 0} unsynced change
                  {(sync.data?.changedFiles.length ?? 0) === 1 ? '' : 's'}
                  {(sync.data?.conflicts.length ?? 0) > 0 ? ` · ${sync.data?.conflicts.length} conflict(s)` : ''}
                </>
              )}
            </span>
          </div>
          {notice !== null && (
            <div className="px-4 pt-3" role="status">
              <Callout tone={notice.tone}>{notice.text}</Callout>
            </div>
          )}
          {list.isError && (
            <div className="p-4">
              <Callout tone="danger">{errorMessage(list.error)}</Callout>
            </div>
          )}
          <div className="overflow-x-auto">
            <table className="w-full min-w-[860px] border-collapse text-sm">
              <caption className="sr-only">Test cases</caption>
              <thead>
                <tr className="text-left text-xs uppercase tracking-[0.05em] text-muted">
                  <th className="w-12 px-4 py-2.5 font-medium">
                    <input
                      type="checkbox"
                      aria-label="Select all on this page"
                      className="h-[18px] w-[18px] accent-primary"
                      checked={allOnPage}
                      disabled={items.length === 0}
                      onChange={toggleAll}
                    />
                  </th>
                  <th scope="col" className="px-2 py-2.5 font-medium">Key</th>
                  <th scope="col" className="px-2 py-2.5 font-medium">Title</th>
                  <th scope="col" className="px-2 py-2.5 font-medium">Priority</th>
                  <th scope="col" className="px-2 py-2.5 font-medium">Learned script</th>
                  <th scope="col" className="px-2 py-2.5 font-medium">Last result</th>
                  <th scope="col" className="px-4 py-2.5 font-medium">Owner</th>
                </tr>
              </thead>
              <tbody ref={rowsRef} onKeyDown={onRowsKey}>
                {list.isLoading &&
                  [0, 1, 2, 3].map((i) => (
                    <tr key={i} className="border-t border-divider-row">
                      <td colSpan={7} className="px-4 py-3">
                        <Skeleton className="h-8" />
                      </td>
                    </tr>
                  ))}
                {items.map((c) => {
                  const sel = selected.has(c.id);
                  const s2 = c.tags.includes(S2_GENERATED_TAG);
                  const tags = c.tags.filter((t) => t !== S2_GENERATED_TAG);
                  return (
                    <tr key={c.id} aria-selected={sel} className={cn('border-t border-divider-row', sel && 'bg-surface-selected')}>
                      <td className="px-4 py-3">
                        <input
                          type="checkbox"
                          aria-label={`Select ${c.key}`}
                          className="h-[18px] w-[18px] accent-primary"
                          checked={sel}
                          onChange={() => toggle(c)}
                        />
                      </td>
                      <td className="whitespace-nowrap px-2 py-3 font-mono text-[13px]">{c.key}</td>
                      <td className="px-2 py-3">
                        <a
                          href={`/p/${encodeURIComponent(projectKey)}/cases/${encodeURIComponent(c.key)}`}
                          onClick={onTitle(c.key)}
                          className="font-medium text-primary-text no-underline hover:underline"
                        >
                          {c.title}
                        </a>
                        <div className="text-xs text-muted">
                          {s2 ? 'generated by S2 · needs review' : tags.length > 0 ? tags.join(' · ') : 'No tags'}
                        </div>
                      </td>
                      <td className="px-2 py-3">{c.priority}</td>
                      <td className="px-2 py-3 text-[13px]">{learnedLabel(c)}</td>
                      <td className="px-2 py-3">
                        {c.lastResult !== null ? (
                          <StatusPill status={c.lastResult.verdict} />
                        ) : c.status === 'draft' ? (
                          <StatusPill status="draft" />
                        ) : (
                          <span className="text-[13px] text-muted">Not run yet</span>
                        )}
                      </td>
                      <td className="px-4 py-3">{c.owner !== undefined && c.owner !== '' ? c.owner : <span className="text-muted">Unassigned</span>}</td>
                    </tr>
                  );
                })}
              </tbody>
            </table>
          </div>
          {list.isSuccess && items.length === 0 && (
            <div className="p-4">
              <EmptyState
                action={
                  q !== '' || lastResult !== undefined ? (
                    <Button
                      size="sm"
                      onClick={() => {
                        setLastResult(undefined);
                        setQuery('');
                      }}
                    >
                      Clear filters
                    </Button>
                  ) : undefined
                }
              >
                {q !== '' || lastResult !== undefined
                  ? 'No test cases match this filter.'
                  : suiteId !== undefined
                    ? 'This suite has no test cases yet. Use New test case to add one.'
                    : 'This project has no test cases yet. Use New test case to add the first one.'}
              </EmptyState>
            </div>
          )}
          <div className="flex flex-wrap items-center justify-between gap-2.5 border-t border-divider px-4 py-3 text-[13px] text-secondary">
            <span>
              Showing {items.length} of {total}
            </span>
            <span className="flex items-center gap-2.5">
              <Button size="sm" disabled={page <= 1} onClick={() => onSearch({ ...search, page: page - 1 <= 1 ? undefined : page - 1 })}>
                Previous
              </Button>
              <span>
                Page {page} of {pageCount}
              </span>
              <Button size="sm" disabled={page >= pageCount} onClick={() => onSearch({ ...search, page: page + 1 })}>
                Next
              </Button>
            </span>
          </div>
        </Card>
      </div>
      <TagDialog
        key={tagOpen ? 'open' : 'closed'}
        open={tagOpen}
        onOpenChange={setTagOpen}
        count={n}
        busy={bulk.isPending}
        onApply={(add, remove) =>
          bulk.mutate(
            { ids, action: 'tag', add, remove },
            {
              onSuccess: () => {
                setTagOpen(false);
                void afterBulk(`Updated tags on ${n} case${n === 1 ? '' : 's'}`);
              },
            },
          )
        }
      />
      <RunLauncherDialog
        open={runOpen}
        onOpenChange={setRunOpen}
        projectKey={projectKey}
        caseKeys={[...selected.values()]}
        onStarted={(runId) => navigate(`/p/${encodeURIComponent(projectKey)}/runs/${encodeURIComponent(runId)}/live`)}
      />
      <AddToPlanDialog
        open={planOpen}
        onOpenChange={setPlanOpen}
        projectKey={projectKey}
        caseIds={ids}
        onDone={(text) => {
          setNotice({ tone: 'success', text });
          setSelected(new Map());
        }}
      />
    </>
  );
}
